import { PGlite } from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec('create table materials(id uuid primary key,name text);');
await db.exec(await readFile(new URL('../supabase/sql/14_purchase_orders.sql',import.meta.url),'utf8'));
const ids=['11111111-1111-4111-8111-111111111111','22222222-2222-4222-8222-222222222222','33333333-3333-4333-8333-333333333333','44444444-4444-4444-8444-444444444444'];
const [material,po,line,receipt]=ids;
await db.query('insert into materials values($1,$2)',[material,'Test elbow']);
await db.query('insert into purchase_orders(id,number,supplier) values($1,$2,$3)',[po,'TEST-001','Test supplier']);
await db.query('insert into purchase_order_lines(id,purchase_order_id,material_id,unit,quantity) values($1,$2,$3,$4,10)',[line,po,material,'ea']);
await assert.rejects(()=>db.query('select record_po_receipt($1,$2,4)',[receipt,line]),/Only ordered/);
await db.query('select set_po_status($1,$2)',[po,'ordered']);
await db.query('select record_po_receipt($1,$2,4)',[receipt,line]);
await db.query('select record_po_receipt($1,$2,4)',[receipt,line]);
assert.equal((await db.query('select count(*)::int n from purchase_order_receipts')).rows[0].n,1);
await assert.rejects(()=>db.query('select record_po_receipt($1,$2,5)',[receipt,line]),/different details/);
await assert.rejects(()=>db.query('select record_po_receipt(gen_random_uuid(),$1,7)',[line]),/exceeds/);
await assert.rejects(()=>db.query('select set_po_status($1,$2)',[po,'cancelled']),/cannot be cancelled/);
await db.query('select record_po_receipt(gen_random_uuid(),$1,6)',[line]);
assert.equal(Number((await db.query('select sum(quantity) n from purchase_order_receipts')).rows[0].n),10);
await assert.rejects(()=>db.query('select record_po_receipt(gen_random_uuid(),$1,0.01)',[line]),/exceeds/);
const {purchaseStatus,outstandingByMaterial}=await import('../src/lib/purchasing.js');
const orders=[{id:po,status:'ordered'},{id:'draft',status:'draft'},{id:'cancelled',status:'cancelled'}];
const lines=[{purchase_order_id:po,material_id:material,unit:'ea',quantity:10,received:4},{purchase_order_id:'draft',material_id:material,unit:'ea',quantity:20,received:0},{purchase_order_id:'cancelled',material_id:material,unit:'ea',quantity:30,received:0}];
assert.equal(outstandingByMaterial(orders,lines).get(`${material}:ea`),6);
assert.equal(purchaseStatus(orders[0],lines),'partially received');
assert.equal(purchaseStatus(orders[0],[{...lines[0],received:10}]),'received');
console.log('PASS: schema, draft receipt guard, ordered transition, idempotent receipt, payload conflict, over-delivery guard, cancellation guard, full delivery, outstanding quantities, status derivation');
await db.close();
